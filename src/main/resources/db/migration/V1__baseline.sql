CREATE TABLE IF NOT EXISTS projects (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(160) NOT NULL, root_path VARCHAR(2048) NOT NULL,
 cockpit_project_id VARCHAR(160) NOT NULL, workflow_id VARCHAR(160) NOT NULL);
CREATE TABLE IF NOT EXISTS templates (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(160) NOT NULL, kind VARCHAR(32) NOT NULL, questions_json TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS interviews (
 id VARCHAR(36) PRIMARY KEY, project_id VARCHAR(36) NOT NULL, template_id VARCHAR(36) NOT NULL,
 kind VARCHAR(32) NOT NULL, title VARCHAR(300) NOT NULL, status VARCHAR(32) NOT NULL,
 answers_json TEXT NOT NULL, question_index INTEGER NOT NULL, followups INTEGER NOT NULL,
 current_question TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS specs (
 id VARCHAR(50) PRIMARY KEY, project_id VARCHAR(36) NOT NULL, title VARCHAR(300) NOT NULL,
 slug VARCHAR(120) NOT NULL, status VARCHAR(24) NOT NULL, body TEXT NOT NULL,
 dependencies_json TEXT NOT NULL, spec_path VARCHAR(280) NOT NULL);
CREATE TABLE IF NOT EXISTS dispatch_log (
 spec_id VARCHAR(50) PRIMARY KEY, state VARCHAR(24) NOT NULL, response TEXT NOT NULL);

CREATE TABLE IF NOT EXISTS spec_templates (
 id VARCHAR(36) PRIMARY KEY, name VARCHAR(160) NOT NULL, content TEXT NOT NULL, is_default BOOLEAN NOT NULL);
